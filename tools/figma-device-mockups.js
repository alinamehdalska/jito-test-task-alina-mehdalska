// bezels would nest every prototype destination inside a parent frame and break the 48
// reactions wired the same day. Figma's presentation view also draws its own device
// chrome, so a bezel there would double up. The board therefore holds clones, and it is
// generated by this script rather than maintained by hand — regeneration, not vigilance,
// is what keeps it from drifting. Same reasoning as the 1:1 stylescape clones.

const page = await figma.getNodeByIdAsync('271:2');   // 07 · Presentation
await figma.setCurrentPageAsync(page);
const get = (id) => figma.getNodeByIdAsync(id);
const kids = (n) => ('children' in n && n.children) ? n.children : [];
const deep = (n, p) => { const o = []; const w = (x) => { if (p(x)) o.push(x); for (const c of kids(x)) w(c); }; w(n); return o; };

// Seed every bound paint with the variable's real colour — a placeholder base renders as
// the placeholder if resolution lags, while still reporting bound: true (agreement 1).
const resolve = async (id) => {
  const v = await figma.variables.getVariableByIdAsync(id);
  const c = v.valuesByMode[Object.keys(v.valuesByMode)[0]];
  return { v, c: { r: c.r, g: c.g, b: c.b } };
};
const paint = (seed, v) => figma.variables.setBoundVariableForPaint({ type: 'SOLID', color: seed }, 'color', v);
const sand50 = await resolve('VariableID:33:2');
const n900 = await resolve('VariableID:1:57');    // the file's warm black — the same tint
const n700 = await resolve('VariableID:1:55');    // every shadow in the system is built on

// iPhone 15 Pro. 393 x 852 is its logical size, which is what every frame is drawn at —
// no scaling, so no rewritten font sizes and no detached styles. The Dynamic Island
// already lives in each screen's own Apple status bar, so the bezel adds enclosure and
// hardware buttons only; drawing a second notch would put two islands on every screen.
const BEZEL = 16, OUTER_W = 425, OUTER_H = 884, OUTER_R = 71, SCREEN_R = 55;
const BUTTONS = [
  ['btn-action', 0, 175, 28], ['btn-volume-up', 0, 225, 52],
  ['btn-volume-down', 0, 292, 52], ['btn-side', OUTER_W - 3, 245, 88]
];

const styles = await figma.getLocalTextStylesAsync();
const style = (n) => styles.find((s) => s.name === n);
const capStyle = style('Subhead Emphasized');
await figma.loadFontAsync(capStyle.fontName);

const buildDevice = async (screenId, caption, rail) => {
  const cell = figma.createAutoLayout('VERTICAL', { name: 'cell — ' + caption, itemSpacing: 16 });
  rail.appendChild(cell);
  cell.fills = [];
  cell.counterAxisAlignItems = 'CENTER';

  const device = figma.createFrame();
  device.name = 'iPhone 15 Pro';
  cell.appendChild(device);
  device.resize(OUTER_W, OUTER_H);               // resize BEFORE sizing modes — it resets them
  device.layoutSizingHorizontal = 'FIXED';
  device.layoutSizingVertical = 'FIXED';
  device.cornerRadius = OUTER_R;                 // 71 = 55 + 16, so the bezel is concentric
  device.clipsContent = false;
  device.fills = [paint(n900.c, n900.v)];
  device.effectStyleId = 'S:cec7ac1212d467f45f964796ec815dc64dcdc4b8,';   // Shadow LG

  const clone = (await get(screenId)).clone();
  device.appendChild(clone);
  clone.x = BEZEL; clone.y = BEZEL;
  // The screen well is cut on the clone itself rather than in a wrapper frame: a frame's
  // clipsContent respects its corner radius, so this rounds the screen in one property.
  clone.cornerRadius = SCREEN_R;
  clone.clipsContent = true;

  // A clone carries the original's reactions, all pointing at frames on 04 · Screens.
  // Prototype links are per-page, so those would be dangling cross-page destinations here.
  for (const n of deep(clone, (x) => 'reactions' in x && x.reactions && x.reactions.length)) await n.setReactionsAsync([]);
  if (clone.reactions && clone.reactions.length) await clone.setReactionsAsync([]);

  for (const [name, x, y, h] of BUTTONS) {
    const b = figma.createRectangle();
    b.name = name;
    device.appendChild(b);
    b.resize(3, h); b.x = x; b.y = y;
    b.cornerRadius = 1.5;
    b.fills = [paint(n700.c, n700.v)];
  }

  const cap = figma.createText();
  cell.appendChild(cap);
  cap.characters = caption;
  await cap.setTextStyleIdAsync(capStyle.id);
  return device.id;
};

